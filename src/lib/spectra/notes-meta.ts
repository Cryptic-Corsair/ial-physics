import type { UnitCode } from "./types";

/* ═══════════════════════════════════════════════════════════════
   the notes card index — who has a note, where

   The shell (club-app) needs to know *that* a topic has a revision
   note — its id, unit, topic, title and spec range — long before it
   needs the note itself. This index carries exactly that, so the
   full docs (notes.ts, ~half a megabyte of source) never land in
   the first-paint bundle; they ride in the lazy reader chunk.

   GENERATED by scripts/gen-notes-meta.ts from notes.ts — re-run it
   after adding or retitling a note doc. notes.ts asserts the two
   stay in step in dev, so drift is loud, not silent.
   ═══════════════════════════════════════════════════════════════ */

export interface NotesMeta {
  /** note doc id, e.g. "wph11-t02" */
  id: string;
  unitCode: UnitCode;
  /** topic id inside the unit, e.g. "t02" */
  topicId: string;
  kicker: string;
  title: string;
  source: string;
  /** first → last spec number covered, e.g. "2.2 → 2.16" */
  specRange: string;
}

export const NOTES_META: NotesMeta[] = [
  {
    id: "wph11-t01",
    unitCode: "WPH11",
    topicId: "t01",
    kicker: "Physics Unit 1 · Mechanics — the complete WPH11 note, statement by statement",
    title: "Forces, motion and energy",
    source:
      "the complete WPH11 Mechanics note — built from the Pearson Edexcel IAL Physics specification (2018, Issue 3), WPH11/01 question papers, mark schemes and Principal Examiners' reports, 2019–2025",
    specRange: "1 → 22",
  },
  {
    id: "wph11-t02",
    unitCode: "WPH11",
    topicId: "t02",
    kicker: "Physics Unit 1 · Materials — the complete WPH11 note, statement by statement",
    title: "Materials — fluids, viscosity and elasticity",
    source:
      "the complete WPH11 Materials note — built from the Pearson Edexcel IAL Physics specification (2018, Issue 3), WPH11/01 question papers, mark schemes and Principal Examiners' reports, 2019–2025",
    specRange: "23 → 32",
  },
];

export function getNotesMeta(docId: string): NotesMeta | undefined {
  return NOTES_META.find((m) => m.id === docId);
}

export function getNotesMetaForTopic(
  unitCode: string,
  topicId: string,
): NotesMeta | undefined {
  return NOTES_META.find((m) => m.unitCode === unitCode && m.topicId === topicId);
}
